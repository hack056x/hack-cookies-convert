var CookieConverter = (function () {
    'use strict';

    var TRUE_RE = /^(?:true|verdadero|verdadeiro|vrai|wahr)$/i;
    var FALSE_RE = /^(?:false|falso|faux|falsch)$/i;
    var NETSCAPE_HEADER = '# Netscape HTTP Cookie File\n# https://curl.se/docs/http-cookies.html\n# Generated by Cookie Converter extension\n\n';

    function isBool(s) { return TRUE_RE.test(s) || FALSE_RE.test(s); }
    function isNum(s) { return /^-?\d+(?:\.\d+)?$/.test(s); }
    function isPath(s) { return s.charAt(0) === '/'; }
    function str(v) { return v == null ? '' : String(v); }
    function flag(v) { return v === true || v === 1 || /^true$/i.test(str(v)); }

    function urlDecode(s) {
        s = s.replace(/\+/g, ' ');
        try { return decodeURIComponent(s); }
        catch (e) { return s.replace(/%([0-9a-f]{2})/gi, function (m, hex) { return String.fromCharCode(parseInt(hex, 16)); }); }
    }
    function isUrlEncoded(s) { return /%09%2F%09(?:TRUE|FALSE)/i.test(s); }

    function base64Decode(s) {
        s = s.replace(/-/g, '+').replace(/_/g, '/').replace(/[^A-Za-z0-9+\/]/g, '');
        if (s.length % 4 === 1) s = s.slice(0, -1);
        while (s.length % 4) s += '=';
        var bin;
        try { bin = atob(s); } catch (e) { return ''; }
        try {
            var bytes = new Uint8Array(bin.length);
            for (var i = 0; i < bin.length; i++) bytes[i] = bin.charCodeAt(i);
            return new TextDecoder('utf-8').decode(bytes);
        } catch (e) { return bin; }
    }

    function cookie(domain, path, secure, expiry, name, value) {
        var exp = Number(expiry);
        return {
            domain: domain,
            path: path.indexOf('/') !== -1 ? path : '',
            secure: TRUE_RE.test(secure),
            expires: isFinite(exp) && exp > 0 ? exp : 0,
            name: name,
            value: value,
            httpOnly: false
        };
    }

    function trimAll(list) { return list.map(function (x) { return x.trim(); }); }

    function solid(f, k) {
        for (var i = 0; i < k && i < f.length; i++) if (/\s/.test(f[i])) return false;
        return true;
    }
    function isExpiry(s) { return s === '' || isNum(s); }

    function fullLine(f) {
        if (f.length >= 7 && isPath(f[2]) && isBool(f[3]) && isExpiry(f[4]) && solid(f, 6)) return cookie(f[0], f[2], f[3], f[4], f[5], f[6]);
        return null;
    }

    function partialLine(f) {
        var n = f.length;
        if (n >= 7 && isPath(f[2]) && (isBool(f[3]) || isNum(f[4])) && solid(f, 6)) return cookie(f[0], f[2], f[3], f[4], f[5], f[6]);
        if (n >= 6 && isPath(f[1]) && !isPath(f[2]) && (isBool(f[2]) || isNum(f[3])) && solid(f, 5)) {
            return cookie(f[0], f[1], f[2], f[3], f[4], f[5]);
        }
        if (n === 6 && isPath(f[2]) && solid(f, 5)) {
            if (isBool(f[3]) && isNum(f[4]) && solid(f, 6)) return cookie(f[0], f[2], f[3], f[4], f[5], '');
            if (isBool(f[3]) && !isNum(f[4])) return cookie(f[0], f[2], f[3], '0', f[4], f[5]);
            if (isNum(f[3])) return cookie(f[0], f[2], 'FALSE', f[3], f[4], f[5]);
        }
        return null;
    }

    function parseLine(line) {
        var splits = [], i, c;
        if (line.indexOf('\t') !== -1) splits.push(trimAll(line.split('\t')));
        splits.push(trimAll(line.replace(/\t/g, ' ').split(' ')), line.split(/[ \t\u00A0]+/));
        for (i = 0; i < splits.length; i++) if ((c = fullLine(splits[i]))) return c;
        for (i = 0; i < splits.length; i++) if ((c = partialLine(splits[i]))) return c;
        return null;
    }

    function parseLineLoose(line) {
        var t = trimAll(line.replace(/\t/g, ' ').split(' '));
        if (t.length < 6) return null;
        var p = t[2].indexOf('/') !== -1 ? 2 : t[1].indexOf('/') !== -1 ? 1 : 0;
        return cookie(t[0], p ? t[p] : '', p ? t[p + 1] : '', p ? t[p + 2] : '',
            t.length === 6 ? t[4] : t[5], t.length === 6 ? t[5] : t[6]);
    }

    function parseNetscape(text, loose) {
        var cookies = [], skipped = 0;
        text.split(/\r\n|\r|\n/).forEach(function (line) {
            line = line.replace(/^\s+/, '');
            var httpOnly = false;
            if (/^#HttpOnly_/i.test(line)) { httpOnly = true; line = line.slice(10); }
            else if (!line || line.charAt(0) === '#') return;
            var c = parseLine(line) || (loose ? parseLineLoose(line) : null);
            if (!c) { skipped++; return; }
            c.httpOnly = httpOnly;
            cookies.push(c);
        });
        return { cookies: cookies, skipped: skipped };
    }

    function toStrictJson(s) {
        var out = '', i = 0, n = s.length, word = /[A-Za-z_$][\w$]*/y;
        while (i < n) {
            var ch = s.charAt(i);
            if (ch === '"' || ch === "'" || ch === '`') {
                var j = i + 1, buf = '';
                while (j < n && s.charAt(j) !== ch) {
                    var c = s.charAt(j);
                    if (c === '\\' && j + 1 < n) {
                        var next = s.charAt(j + 1);
                        buf += next === "'" || next === '`' ? next : c + next;
                        j += 2; continue;
                    }
                    buf += c === '"' ? '\\"' : c;
                    j++;
                }
                out += '"' + buf + (j < n ? '"' : '');
                i = j + 1; continue;
            }
            word.lastIndex = i;
            var m = /[A-Za-z_$]/.test(ch) && word.exec(s);
            if (m) {
                var w = m[0], k = i + w.length;
                while (k < n && /\s/.test(s.charAt(k))) k++;
                if (s.charAt(k) === ':') out += '"' + w + '"';
                else if (w === 'True') out += 'true';
                else if (w === 'False') out += 'false';
                else if (w === 'None' || w === 'undefined') out += 'null';
                else out += w;
                i += w.length; continue;
            }
            out += ch; i++;
        }
        return out;
    }

    function salvageObjects(s) {
        var found = [], starts = [], inString = false;
        for (var i = 0; i < s.length; i++) {
            var ch = s.charAt(i);
            if (inString) { if (ch === '\\') i++; else if (ch === '"') inString = false; }
            else if (ch === '"') inString = true;
            else if (ch === '{') starts.push(i);
            else if (ch === '}' && starts.length) {
                var start = starts.pop();
                try {
                    var o = JSON.parse(s.slice(start, i + 1));
                    if (o && typeof o === 'object' && 'name' in o) found.push(o);
                } catch (e) {}
            }
        }
        return found;
    }

    function parseJson(text) {
        var data;
        try { data = JSON.parse(text); }
        catch (e) {
            var strict = toStrictJson(text);
            try { data = JSON.parse(strict); }
            catch (e2) {
                data = salvageObjects(strict);
                if (!data.length) return { error: e.message };
            }
        }
        var list = Array.isArray(data) ? data
            : data && Array.isArray(data.cookies) ? data.cookies
            : data && typeof data === 'object' && 'name' in data ? [data]
            : null;
        if (!list) return { cookies: [], skipped: 0 };
        var cookies = [], skipped = 0;
        list.forEach(function (c) {
            if (!c || typeof c !== 'object') { skipped++; return; }
            var domain = str(c.domain != null ? c.domain : c.host).trim();
            if (!domain && c.url) { try { domain = new URL(c.url).hostname; } catch (e) {} }
            if (!domain || c.name == null) { skipped++; return; }
            if (c.hostOnly === false && domain.charAt(0) !== '.') domain = '.' + domain;
            var exp = [c.expirationDate, c.expires, c.expiry, c.expiration].filter(function (v) { return v != null; })[0];
            if (typeof exp === 'string' && !isNum(exp)) exp = Date.parse(exp) / 1000;
            exp = Number(exp);
            cookies.push({
                domain: domain,
                path: str(c.path) || '/',
                secure: flag(c.secure != null ? c.secure : c.isSecure),
                httpOnly: flag(c.httpOnly != null ? c.httpOnly : c.isHttpOnly),
                expires: c.session !== true && isFinite(exp) && exp > 0 ? exp : 0,
                name: str(c.name),
                value: str(c.value)
            });
        });
        return { cookies: cookies, skipped: skipped };
    }

    function toJson(cookies, simple) {
        if (simple) {
            return JSON.stringify(cookies.map(function (c) {
                var o = { domain: c.domain };
                if (c.path) o.path = c.path;
                o.name = c.name; o.value = c.value;
                return o;
            }));
        }
        return JSON.stringify(cookies.map(function (c) {
            var o = { domain: c.domain };
            if (c.expires > 0) o.expirationDate = c.expires;
            o.hostOnly = c.domain.charAt(0) !== '.';
            o.httpOnly = c.httpOnly;
            o.name = c.name;
            o.path = c.path || '/';
            o.secure = c.secure;
            o.session = !(c.expires > 0);
            o.value = c.value;
            return o;
        }), null, 4);
    }

    function toNetscape(cookies) {
        var clean = function (s) { return str(s).replace(/[\t\r\n]/g, ''); };
        return NETSCAPE_HEADER + cookies.map(function (c) {
            var domain = clean(c.domain);
            return (c.httpOnly ? '#HttpOnly_' : '') + [
                domain,
                domain.charAt(0) === '.' ? 'TRUE' : 'FALSE',
                clean(c.path) || '/',
                c.secure ? 'TRUE' : 'FALSE',
                Math.floor(c.expires),
                clean(c.name),
                clean(c.value)
            ].join('\t');
        }).join('\n') + '\n';
    }

    function convert(raw, now, simple) {
        var text = str(raw);
        if (!text.trim()) return { from: null };
        var plain = isUrlEncoded(text) ? urlDecode(text) : text;
        var json = /^[\s\uFEFF]*[\[{]/.test(plain);
        var candidates = [{ text: plain, loose: /FALSE|TRUE| FALSO /.test(plain) && plain.indexOf('/') !== -1 }];
        var b64 = json ? '' : base64Decode(text);
        if (b64) candidates.push({ text: isUrlEncoded(b64) ? urlDecode(b64) : b64, loose: true });

        var jsonError = null;
        for (var i = 0; i < candidates.length; i++) {
            var t = candidates[i].text.replace(/^\uFEFF/, '');
            var from = 'netscape', parsed = null;
            if (/^\s*[\[{]/.test(t)) {
                parsed = parseJson(t.trim());
                if (parsed.error) jsonError = jsonError || parsed.error;
                else if (parsed.cookies.length) from = 'json';
            }
            if (from === 'netscape') parsed = parseNetscape(t, candidates[i].loose);
            if (!parsed.cookies.length) continue;
            var expired = 0;
            parsed.cookies.forEach(function (c) { if (now && c.expires > 0 && c.expires < now) expired++; });
            return {
                from: from,
                to: from === 'json' ? 'netscape' : 'json',
                output: from === 'json' ? toNetscape(parsed.cookies) : toJson(parsed.cookies, simple),
                count: parsed.cookies.length,
                expired: expired,
                skipped: parsed.skipped
            };
        }
        return { from: jsonError ? 'json' : 'netscape', error: jsonError ? 'Invalido JSON: ' + jsonError : 'No se encontraron cookies. Compruebe el formato' };
    }

    return { convert: convert };
})();

/* ============================================================
   UI — adaptada al popup (sin analytics, sin botón Convertir)
   ============================================================ */
(function () {
    'use strict';

    var $ = function (id) { return document.getElementById(id); };
    var input = $('cookie'), output = $('result'), stat = $('stat');
    var inPane = $('in-pane'), outPane = $('out-pane');
    var copyBtn = $('copy'), downloadBtn = $('download'), clearBtn = $('clear');
    var tabs = { json: $('to-json'), netscape: $('to-netscape') };
    var simple = $('simple');
    var target = 'json';
    var last = { from: null };
    var timer = 0;

    function setTarget(to) {
        target = to;
        var json = to === 'json';
        tabs.json.setAttribute('aria-pressed', String(json));
        tabs.netscape.setAttribute('aria-pressed', String(!json));
        $('in-label').textContent = json ? 'Netscape' : 'JSON';
        $('out-label').textContent = json ? 'JSON' : 'Netscape';
        input.placeholder = json ? 'Pega cookies Netscape' : 'Pega cookies JSON';
        $('simple-option').classList.toggle('off', !json);
    }

    function plural(n, word) { return n + ' ' + word + (n === 1 ? '' : 's'); }

    function render() {
        var r = CookieConverter.convert(input.value, Date.now() / 1000, simple.checked);
        last = r;
        clearBtn.disabled = !input.value;
        outPane.classList.toggle('err', !!r.error);
        stat.title = r.error || '';
        var ok = !!r.output;
        copyBtn.disabled = downloadBtn.disabled = !ok;
        if (!r.from) { output.value = ''; stat.textContent = ''; return; }
        if (r.error) { output.value = ''; stat.textContent = r.error; return; }
        if (r.to !== target) setTarget(r.to);
        output.value = r.output;
        stat.textContent = plural(r.count, 'cookie') + (r.skipped ? ' · ' + plural(r.skipped, 'línea') + ' saltada(s)' : '');
        if (r.expired && !(r.to === 'json' && simple.checked)) {
            var warn = document.createElement('span');
            warn.className = 'warn';
            warn.textContent = r.expired + ' expiradas';
            stat.appendChild(document.createTextNode(' · '));
            stat.appendChild(warn);
        }
    }

    function load(text) { input.value = text; render(); }

    function readFile(file) {
        if (!file) return;
        var reader = new FileReader();
        reader.onload = function () { load(String(reader.result)); };
        reader.readAsText(file);
    }

    input.addEventListener('input', function (e) {
        clearTimeout(timer);
        if (e.inputType === 'insertFromPaste' || e.inputType === 'insertFromDrop') render();
        else timer = setTimeout(render, 250);
    });
    input.addEventListener('keydown', function (e) {
        if (e.key === 'Enter' && (e.metaKey || e.ctrlKey)) { e.preventDefault(); render(); }
    });

    Object.keys(tabs).forEach(function (to) {
        tabs[to].addEventListener('click', function () {
            if (to === target) return;
            if (last.output) load(last.output);
            else setTarget(to);
        });
    });

    try { if (localStorage.getItem('cookieConverter.simple') === '1') simple.checked = true; } catch (e) {}
    simple.addEventListener('change', function () {
        try { localStorage.setItem('cookieConverter.simple', simple.checked ? '1' : '0'); } catch (e) {}
        render();
    });

    clearBtn.addEventListener('click', function () {
        input.value = ''; render(); input.focus();
    });

    $('open').addEventListener('click', function () { $('file').click(); });
    $('file').addEventListener('change', function () { readFile(this.files[0]); this.value = ''; });

    var selectedOnFocus = false;
    output.addEventListener('focus', function () { output.select(); selectedOnFocus = true; });
    output.addEventListener('mouseup', function (e) { if (selectedOnFocus) e.preventDefault(); selectedOnFocus = false; });

    copyBtn.addEventListener('click', function () {
        var text = output.value;
        var done = function () {
            copyBtn.textContent = 'Copiado';
            setTimeout(function () { copyBtn.textContent = 'Copiar'; }, 1500);
        };
        var fallback = function () {
            output.focus(); output.select();
            try { if (document.execCommand('copy')) done(); } catch (e) {}
        };
        if (navigator.clipboard && navigator.clipboard.writeText) navigator.clipboard.writeText(text).then(done, fallback);
        else fallback();
    });

    downloadBtn.addEventListener('click', function () {
        var json = last.to === 'json';
        var blob = new Blob([output.value], { type: json ? 'application/json' : 'text/plain' });
        var a = document.createElement('a');
        a.href = URL.createObjectURL(blob);
        a.download = json ? 'cookies.json' : 'cookies.txt';
        document.body.appendChild(a);
        a.click(); a.remove();
        setTimeout(function () { URL.revokeObjectURL(a.href); }, 1000);
    });

    var hasFiles = function (e) { return e.dataTransfer && [].indexOf.call(e.dataTransfer.types || [], 'Files') !== -1; };
    document.addEventListener('dragover', function (e) {
        if (!hasFiles(e)) return;
        e.preventDefault(); inPane.classList.add('drop');
    });
    document.addEventListener('dragleave', function (e) {
        if (!e.relatedTarget) inPane.classList.remove('drop');
    });
    document.addEventListener('drop', function (e) {
        inPane.classList.remove('drop');
        if (!hasFiles(e)) return;
        e.preventDefault(); readFile(e.dataTransfer.files[0]);
    });

    document.addEventListener('paste', function (e) {
        var el = e.target;
        if (el && (el.tagName === 'TEXTAREA' || (el.tagName === 'INPUT' && el.type !== 'checkbox') || el.isContentEditable)) return;
        var text = e.clipboardData && e.clipboardData.getData('text');
        if (!text) return;
        e.preventDefault(); load(text);
    });

    if (input.value) render();
    input.focus({ preventScroll: true });
})();